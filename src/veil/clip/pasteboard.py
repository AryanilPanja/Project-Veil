"""The macOS general pasteboard as veil's clipboard backend (macOS port).

Talks to AppKit through ctypes and the Objective-C runtime: no pyobjc (about 100 ms of imports)
and no pbcopy/pbpaste subprocess. Loading AppKit takes about 1 ms; a message send about 1 us.

Reading mirrors the Linux backends: the offered types are listed first (`[pb types]`), mapped to
the MIME-ish names `io.classify` understands, and only a plain-text type is ever requested. The
size is checked before the text is copied out. Writing offers one content type, plain UTF-8 text,
plus the org.nspasteboard.* marker types that clipboard managers (Maccy, Raycast, Alfred, Paste,
Spotlight history) honour by not storing the entry, so veil's output stays out of their history.

macOS has no primary selection: `Selection.PRIMARY` reads as empty. Errors carry a fixed message,
never clipboard text.
"""

import ctypes
import functools
import sys
from collections.abc import Callable, Sequence
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Any

from veil.clip import recent
from veil.clip.io import MAX_CLIP_BYTES, ClipContent, Kind, Selection, classify, plain_only
from veil.errors import ClipboardError

_LIBOBJC = "/usr/lib/libobjc.A.dylib"
_APPKIT = "/System/Library/Frameworks/AppKit.framework/AppKit"
_NSUTF8_STRING_ENCODING = 4

CONCEALED = "org.nspasteboard.ConcealedType"
TRANSIENT = "org.nspasteboard.TransientType"
AUTO_GENERATED = "org.nspasteboard.AutoGeneratedType"
SOURCE = "org.nspasteboard.source"
MARKERS = frozenset({CONCEALED, TRANSIENT, AUTO_GENERATED, SOURCE})
WRITE_UTI = "public.utf8-plain-text"
SOURCE_NAME = "veil"

# Apple UTI (or legacy pasteboard type) -> the name `io.classify` knows. Anything else passes
# through unchanged, so an image (public.png, public.tiff) ends up NON_TEXT.
_UTI_NAMES = {
    "public.utf8-plain-text": "text/plain;charset=utf-8",
    "public.plain-text": "text/plain",
    "NSStringPboardType": "string",
    "public.rtf": "application/rtf",
    "com.apple.flat-rtfd": "application/rtf",
    "public.rtfd": "application/rtf",
    "public.html": "text/html",
}


@dataclass(frozen=True)
class MappedTypes:
    names: tuple[str, ...]  # the classify() vocabulary, markers removed
    secret: bool  # the source marked the content as a concealed password
    total: int  # how many types the pasteboard offered, markers included
    originals: dict[str, str]  # mapped name -> the first UTI that produced it


def map_types(utis: Sequence[str]) -> MappedTypes:
    """Pure: pasteboard UTIs -> classify() names, marker types dropped and noted."""
    names: list[str] = []
    originals: dict[str, str] = {}
    for uti in utis:
        if uti in MARKERS:
            continue
        name = _UTI_NAMES.get(uti, uti)
        names.append(name)
        originals.setdefault(name, uti)
    return MappedTypes(tuple(names), CONCEALED in utis, len(utis), originals)


# --- Objective-C runtime plumbing -------------------------------------------------------------

_ptr = ctypes.c_void_p


@functools.cache
def _runtime() -> tuple[ctypes.CDLL, int]:
    if sys.platform != "darwin":
        raise ClipboardError("the macOS pasteboard is only available on macOS")
    try:
        objc = ctypes.CDLL(_LIBOBJC)
        ctypes.CDLL(_APPKIT)  # registers NSPasteboard with the runtime
        objc.objc_getClass.argtypes = (ctypes.c_char_p,)
        objc.objc_getClass.restype = _ptr
        objc.sel_registerName.argtypes = (ctypes.c_char_p,)
        objc.sel_registerName.restype = _ptr
        objc.objc_autoreleasePoolPush.argtypes = ()
        objc.objc_autoreleasePoolPush.restype = _ptr
        objc.objc_autoreleasePoolPop.argtypes = (_ptr,)
        objc.objc_autoreleasePoolPop.restype = None
        send = ctypes.cast(objc.objc_msgSend, _ptr).value
    except (OSError, AttributeError):
        raise ClipboardError("the macOS pasteboard could not be loaded") from None
    if send is None:
        raise ClipboardError("the macOS pasteboard could not be loaded")
    return objc, send


@functools.cache
def _sel(name: str) -> int:
    objc, _ = _runtime()
    return objc.sel_registerName(name.encode("ascii"))


@functools.cache
def _class(name: str) -> int:
    objc, _ = _runtime()
    found = objc.objc_getClass(name.encode("ascii"))
    if not found:
        raise ClipboardError("the macOS pasteboard could not be loaded")
    return found


@functools.cache
def _prototype(restype: Any, argtypes: tuple[Any, ...]) -> Callable[..., Any]:
    """One typed objc_msgSend per signature (receiver and selector are always the first two)."""
    _, send = _runtime()
    return ctypes.CFUNCTYPE(restype, _ptr, _ptr, *argtypes)(send)


def _msg(obj: int, selector: str, *args: Any, restype: Any = _ptr, argtypes: tuple = ()) -> Any:
    return _prototype(restype, argtypes)(obj, _sel(selector), *args)


@contextmanager
def _pool():
    objc, _ = _runtime()
    token = objc.objc_autoreleasePoolPush()
    try:
        yield
    finally:
        objc.objc_autoreleasePoolPop(token)


def _pasteboard() -> int:
    board = _msg(_class("NSPasteboard"), "generalPasteboard")
    if not board:
        raise ClipboardError("the macOS pasteboard is not available")
    return board


def _ns_string(text: str) -> int:
    """An autoreleased NSString from Python text (length-based, so NUL characters survive)."""
    try:
        data = text.encode("utf-8")
    except UnicodeEncodeError:
        raise ClipboardError("the text is not valid UTF-8") from None
    raw = _msg(_class("NSString"), "alloc")
    made = _msg(
        raw,
        "initWithBytes:length:encoding:",
        data,
        len(data),
        _NSUTF8_STRING_ENCODING,
        argtypes=(ctypes.c_char_p, ctypes.c_ulong, ctypes.c_ulong),
    )
    if not made:
        raise ClipboardError("the macOS pasteboard rejected the text")
    return _msg(made, "autorelease")


def _py_str(ns_string: int) -> str:
    """An NSString as Python text (length-based, so NUL characters survive)."""
    length = _msg(
        ns_string,
        "lengthOfBytesUsingEncoding:",
        _NSUTF8_STRING_ENCODING,
        restype=ctypes.c_ulong,
        argtypes=(ctypes.c_ulong,),
    )
    return _copy_utf8(ns_string, length)


def _copy_utf8(ns_string: int, length: int) -> str:
    chars = _msg(ns_string, "UTF8String", restype=ctypes.c_void_p)
    if not chars:
        return ""
    try:
        return ctypes.string_at(chars, length).decode("utf-8")
    except UnicodeDecodeError:
        raise ClipboardError("the clipboard text is not valid UTF-8") from None


def _types(board: int) -> list[str]:
    array = _msg(board, "types")
    if not array:
        return []
    count = _msg(array, "count", restype=ctypes.c_ulong)
    found: list[str] = []
    for index in range(count):
        item = _msg(array, "objectAtIndex:", index, argtypes=(ctypes.c_ulong,))
        if item:
            found.append(_py_str(item))
    return found


def _set(board: int, uti: str, text: str) -> None:
    ok = _msg(
        board,
        "setString:forType:",
        _ns_string(text),
        _ns_string(uti),
        restype=ctypes.c_bool,
        argtypes=(_ptr, _ptr),
    )
    if not ok:
        raise ClipboardError("the macOS pasteboard rejected the write")


def _written_by_veil(board: int) -> bool:
    """veil marks its own output as concealed (for clipboard managers); that is not a password."""
    found = _msg(board, "stringForType:", _ns_string(SOURCE), argtypes=(_ptr,))
    return bool(found) and _py_str(found) == SOURCE_NAME


def change_count() -> int:
    """The general pasteboard's change counter: it moves on every copy. About 1 us per call."""
    with _pool():
        return int(_msg(_pasteboard(), "changeCount", restype=ctypes.c_long))


class PasteboardClipboard:
    name = "pasteboard"

    def __init__(self, *, limit: int = MAX_CLIP_BYTES) -> None:
        self._limit = limit

    def read(self, selection: Selection = Selection.CLIPBOARD) -> ClipContent:
        if selection is Selection.PRIMARY:
            return ClipContent(Kind.EMPTY)  # macOS has no primary selection
        with _pool():
            board = _pasteboard()
            mapped = map_types(_types(board))
            secret = mapped.secret and not _written_by_veil(board)
            kind, plain = classify(mapped.names)
            if plain is None:
                return ClipContent(kind, secret=secret, type_count=mapped.total)
            ns_type = _ns_string(mapped.originals[plain])
            text = _msg(board, "stringForType:", ns_type, argtypes=(_ptr,))
            if not text:  # the owner changed in between, or the type has no string form
                return ClipContent(Kind.EMPTY)
            size = _msg(
                text,
                "lengthOfBytesUsingEncoding:",
                _NSUTF8_STRING_ENCODING,
                restype=ctypes.c_ulong,
                argtypes=(ctypes.c_ulong,),
            )
            if size > self._limit:
                raise ClipboardError("the clipboard text is too large")
            return ClipContent(
                Kind.TEXT,
                _copy_utf8(text, size),
                secret=secret,
                type_count=mapped.total,
                plain_only=plain_only(mapped.names),
            )

    def write_text(self, text: str) -> None:
        recent.remember(text)  # before the write: the copy watcher must know it's veil's own
        with _pool():
            board = _pasteboard()
            _msg(board, "clearContents", restype=ctypes.c_long)
            # Markers first: a clipboard manager that reads between our calls sees them
            # before it can see any text.
            _set(board, TRANSIENT, "")
            _set(board, AUTO_GENERATED, "")
            _set(board, CONCEALED, "")
            _set(board, SOURCE, SOURCE_NAME)
            _set(board, WRITE_UTI, text)

    def clear(self, selection: Selection = Selection.CLIPBOARD) -> None:
        if selection is Selection.PRIMARY:
            return
        with _pool():
            _msg(_pasteboard(), "clearContents", restype=ctypes.c_long)
